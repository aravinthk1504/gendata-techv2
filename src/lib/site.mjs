// Relative URLs: Next.js resolves them against metadataBase.
export function alternatesFor(lang, path = "") {
  const own = LANGUAGES.includes(lang) ? lang : DEFAULT_LANGUAGE;
  return {
    canonical: `/${own}${path}`,
    languages: {
      en: `/en${path}`,
      de: `/de${path}`,
      "x-default": `/${DEFAULT_LANGUAGE}${path}`,
    },
  };
}

export function openGraphLocale(lang) {
  return lang === "de" ? "de_DE" : "en_US";
}

// Branded share card generated by src/app/[lang]/opengraph-image.jsx. Pages that
// set their own openGraph object must list it explicitly, because Next.js does
// not merge the file-based image into an overridden openGraph field.
export function defaultShareImage(lang) {
  const own = LANGUAGES.includes(lang) ? lang : DEFAULT_LANGUAGE;
  return { url: `/${own}/opengraph-image`, width: 1200, height: 630, alt: SITE_NAME };
}
