// Single source for the public site URL and route list used by metadata,
// sitemap, robots and structured data. Plain .mjs so node --test can import it.

export const SITE_NAME = "GenData Tech";
export const LANGUAGES = ["en", "de"];
export const DEFAULT_LANGUAGE = "en";

// Override with the SITE_URL environment variable (for example on a staging
// backend). Only https origins (or localhost for development) are accepted.
const FALLBACK_URL = "https://gendatatech.com";

export function siteUrl(env = process.env) {
  const raw = String(env.SITE_URL || FALLBACK_URL).trim();
  try {
    const url = new URL(raw);
    const local = url.hostname === "localhost" || url.hostname === "127.0.0.1";
    if (url.protocol === "https:" || local) return url.origin;
  } catch {
    // Fall through to the default below.
  }
  return FALLBACK_URL;
}

export function absoluteUrl(path = "", env = process.env) {
  return siteUrl(env) + path;
}

